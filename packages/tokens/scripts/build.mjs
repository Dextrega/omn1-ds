// Token build: Figma export → DTCG (normalize) → Style Dictionary (resolve) → outputs.
//
// Outputs (dist/):
//   css/tokens.css          shared tokens on :root; primitives + key + semantic per theme (light / dark)
//   css/alias.css           optional Alias layer (references Primitives directly, mirrors Figma)
//   json/tokens.light.json  resolved values, nested        json/tokens.dark.json
//   json/color-graph.json   un-resolved colour graph (refs + alpha) — used by the runtime ThemeProvider
//   theme.json              Tailwind theme (every value is a var(--omn1-*) reference)
//   figma-variable-map.json Figma variable path → CSS var → Tailwind key (the design-to-code contract)
// And src/generated/data.ts, which tsup bundles into the public TypeScript API.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import StyleDictionary from "style-dictionary";
import { normalize, walk, isToken } from "./normalize.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIST = path.join(ROOT, "dist");
const GEN = path.join(ROOT, "src", "generated");
const PREFIX = "omn1";
const PX_GROUPS = new Set([
  "system",
  "spacement",
  "border-radius",
  "corner-radius",
  "stroke",
  "size",
  "line-height",
  "letter-spacing",
]);
const THEME_LAYERS = ["primitives", "key", "semantic"]; // Dark mode also inverts the primitive ramps

StyleDictionary.registerTransform({
  name: "omn1/name",
  type: "name",
  transform: (token) => token.path.join("-"),
});

// ---- 1. normalize + resolve ---------------------------------------------------------------------
const { shared, light, dark, displayStyles } = normalize(
  path.join(ROOT, "figma-export"),
  path.join(ROOT, "src", "authored"),
);

async function resolveMode(modeTree) {
  const sd = new StyleDictionary({
    tokens: { ...shared, ...modeTree },
    log: { verbosity: "silent", warnings: "warn" },
    platforms: { omn1: { transforms: ["omn1/name"] } },
  });
  const exported = await sd.exportPlatform("omn1");
  const records = [];
  for (const [segs, token] of walk(exported)) {
    records.push({
      path: segs,
      name: token.name ?? segs.join("-"),
      type: token.$type,
      value: token.$value,
      original: token.original?.$value ?? token.$value,
      ext: token.$extensions?.["com.omn1"] ?? {},
    });
  }
  return records;
}

const lightRecs = await resolveMode(light);
const darkRecs = await resolveMode(dark);

const names = (recs) =>
  recs
    .map((r) => r.name)
    .sort()
    .join("\n");
if (names(lightRecs) !== names(darkRecs)) {
  throw new Error("Light and Dark do not define the same tokens. Fix the Figma variable modes.");
}

// ---- 2. helpers -------------------------------------------------------------------------------------
const layerOf = (r) => r.path[0];
const refOf = (orig) =>
  typeof orig === "string" && /^\{[^}]+\}$/.test(orig)
    ? orig.slice(1, -1).split(".").join("-")
    : null;
const cssVar = (name) => `--${PREFIX}-${name}`;

function cssLiteral(r) {
  if (r.type === "fontFamily") return r.value.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(", ");
  if (r.type === "number" && PX_GROUPS.has(r.path[0])) return `${r.value}px`;
  return String(r.value);
}
function cssValue(r) {
  const ref = refOf(r.original);
  if (r.ext.alpha != null) {
    return `color-mix(in srgb, var(${cssVar(ref)}) ${+(r.ext.alpha * 100).toFixed(2)}%, transparent)`;
  }
  return ref ? `var(${cssVar(ref)})` : cssLiteral(r);
}

function applyAlpha(hex, alpha) {
  let h = hex.replace("#", "");
  if (h.length === 3) h = [...h].map((c) => c + c).join("");
  const base = h.length === 8 ? parseInt(h.slice(6), 16) / 255 : 1;
  const a = Math.round(base * alpha * 255);
  return `#${h.slice(0, 6)}${a >= 255 ? "" : a.toString(16).padStart(2, "0")}`;
}
const resolvedColor = (r) => (r.ext.alpha != null ? applyAlpha(r.value, r.ext.alpha) : r.value);

const decl = (r, indent = "  ") => `${indent}${cssVar(r.name)}: ${cssValue(r)};`;
function block(selector, lines, indent = "") {
  return `${indent}${selector} {\n${lines.map((l) => (indent ? indent + l : l)).join("\n")}\n${indent}}\n`;
}
const header = (title) =>
  `/* ${title}\n * Generated by @omn1/tokens from the Figma export. Do not edit by hand. */\n`;

function themeCss(layers, recsFor) {
  const lines = (mode) => [
    `  color-scheme: ${mode};`,
    ...recsFor(mode)
      .filter((r) => layers.includes(layerOf(r)))
      .map((r) => decl(r)),
  ];
  return [
    block(':root,\n[data-theme="light"]', lines("light")),
    block('[data-theme="dark"]', lines("dark")),
    `@media (prefers-color-scheme: dark) {\n${block(":root:not([data-theme])", lines("dark"), "  ")}}\n`,
  ].join("\n");
}

// ---- 2b. effects (Figma effect styles, authored in effects/effects.json) ----------------------------
const effectsSrc = JSON.parse(fs.readFileSync(path.join(ROOT, "effects", "effects.json"), "utf8"));
const effectRecs = Object.entries(effectsSrc["drop-shadow"]).map(([step, tok]) => ({
  name: `shadow-${step}`,
  step,
  figma: tok.$extensions["com.omn1"].figma,
  layers: tok.$value,
}));
const px = (n) => (n === 0 ? "0" : `${n}px`);
const shadowCss = (layers) =>
  layers
    .map(
      (l) =>
        `${px(l.offsetX)} ${px(l.offsetY)} ${px(l.blur)} ${px(l.spread)} color-mix(in srgb, ${l.color} ${+(l.alpha * 100).toFixed(2)}%, transparent)`,
    )
    .join(", ");

// ---- 3. CSS ----------------------------------------------------------------------------------------------
// Only clear what this script owns — tsup also writes into dist/ (index.js, index.cjs, *.d.ts).
for (const f of ["css", "json", "theme.json", "figma-variable-map.json"]) {
  fs.rmSync(path.join(DIST, f), { recursive: true, force: true });
}
fs.mkdirSync(path.join(DIST, "css"), { recursive: true });
fs.mkdirSync(path.join(DIST, "json"), { recursive: true });
fs.mkdirSync(GEN, { recursive: true });

const sharedRecs = lightRecs.filter(
  (r) => !["primitives", "key", "semantic", "alias"].includes(layerOf(r)),
);
const byMode = (m) => (m === "dark" ? darkRecs : lightRecs);

fs.writeFileSync(
  path.join(DIST, "css", "tokens.css"),
  [
    header("OMN1 design tokens"),
    block(":root", [
      ...sharedRecs.map((r) => decl(r)),
      ...effectRecs.map((e) => `  ${cssVar(e.name)}: ${shadowCss(e.layers)};`),
    ]),
    themeCss(THEME_LAYERS, byMode),
  ].join("\n"),
);
fs.writeFileSync(
  path.join(DIST, "css", "alias.css"),
  [header("OMN1 alias tokens (optional layer)"), themeCss(["alias"], byMode)].join("\n"),
);

// ---- 4. JSON + generated TS data ---------------------------------------------------------------------------
const nest = (recs, pick) => {
  const out = {};
  for (const r of recs) {
    let cur = out;
    for (const s of r.path.slice(0, -1)) cur = cur[s] ??= {};
    cur[r.path[r.path.length - 1]] = pick(r);
  }
  return out;
};
const colorRecs = (recs) => recs.filter((r) => r.type === "color");
const graphNode = (r) => {
  const ref = refOf(r.original);
  if (!ref) return { v: r.value };
  return r.ext.alpha != null ? { r: ref, a: r.ext.alpha } : { r: ref };
};
const colorGraph = {
  light: Object.fromEntries(colorRecs(lightRecs).map((r) => [r.name, graphNode(r)])),
  dark: Object.fromEntries(colorRecs(darkRecs).map((r) => [r.name, graphNode(r)])),
};
const sharedValues = nest(sharedRecs, (r) => r.value);
const resolvedTree = (recs) => nest(colorRecs(recs), resolvedColor);

fs.writeFileSync(
  path.join(DIST, "json", "tokens.light.json"),
  JSON.stringify({ ...resolvedTree(lightRecs), ...sharedValues }, null, 2),
);
fs.writeFileSync(
  path.join(DIST, "json", "tokens.dark.json"),
  JSON.stringify({ ...resolvedTree(darkRecs), ...sharedValues }, null, 2),
);
fs.writeFileSync(path.join(DIST, "json", "color-graph.json"), JSON.stringify(colorGraph));
fs.writeFileSync(
  path.join(DIST, "json", "display-styles.json"),
  JSON.stringify(displayStyles, null, 2),
);

const ts = (name, value, doc) =>
  `${doc ? `/** ${doc} */\n` : ""}export const ${name} = ${JSON.stringify(value, null, 2)};\n`;
fs.writeFileSync(
  path.join(GEN, "data.ts"),
  [
    "// Generated by scripts/build.mjs — do not edit.\n",
    ts(
      "colorGraph",
      colorGraph,
      "Un-resolved colour graph per mode: literal (v), reference (r) or reference + alpha (r, a).",
    ),
    ts(
      "tokens",
      {
        light: { ...resolvedTree(lightRecs) },
        dark: { ...resolvedTree(darkRecs) },
        shared: sharedValues,
      },
      "Resolved token values (light / dark colours, shared dimensions).",
    ),
    ts(
      "effects",
      Object.fromEntries(effectRecs.map((e) => [e.step, { figma: e.figma, layers: e.layers }])),
      "Figma effect styles (DropShadow levels) as structured layers; React Native uses the strongest layer.",
    ),
    ts("displayStyles", displayStyles, "Composite Display text styles from Figma."),
    ts("dimensionGroups", [...PX_GROUPS], "Shared token groups whose numeric values are pixels."),
  ].join("\n"),
);

// ---- 5. Tailwind theme -------------------------------------------------------------------------------------------
const v = (name) => `var(${cssVar(name)})`;
const T = {
  colors: {},
  spacing: {},
  borderRadius: {},
  borderWidth: {},
  fontSize: {},
  fontWeight: {},
  letterSpacing: {},
  fontFamily: {},
  boxShadow: {},
};
const put = (obj, segs, value) => {
  let cur = obj;
  for (const s of segs.slice(0, -1)) cur = cur[s] ??= {};
  cur[segs[segs.length - 1]] = value;
};
const sizes = {};
for (const r of lightRecs) {
  const [group, ...rest] = r.path;
  // Key.Global.White/Black FLIP in Dark mode (white is black there), so they live under `global-*`
  // rather than Tailwind's `white` / `black`, which people expect to be constant.
  if (group === "key" && rest[0] === "global") {
    if (rest[1] === "transparent") T.colors.transparent = v(r.name);
    else put(T.colors, ["global", rest[1]], v(r.name));
  } else if (group === "semantic") {
    const [family, ...tail] = rest;
    put(T.colors, [family === "opacity" ? "alpha" : family, ...tail], v(r.name));
  } else if (group === "system" && rest[0] !== "9999") T.spacing[rest[0]] = v(r.name);
  else if (group === "spacement") T.spacing[rest[0]] = v(r.name);
  else if (group === "border-radius") T.borderRadius[rest[0]] = v(r.name);
  else if (group === "corner-radius") T.borderRadius[`corner-${rest[0]}`] = v(r.name);
  else if (group === "stroke") T.borderWidth[rest[0]] = v(r.name);
  else if (group === "size") (sizes[rest[0]] ??= {}).size = v(r.name);
  else if (group === "line-height") (sizes[rest[0]] ??= {}).lh = v(r.name);
  else if (group === "weight") T.fontWeight[rest[0]] = v(r.name);
  else if (group === "letter-spacing") T.letterSpacing[rest[0]] = v(r.name);
  else if (group === "font-family") T.fontFamily[rest[0]] = v(r.name);
}
for (const [k, { size, lh }] of Object.entries(sizes)) {
  T.fontSize[k] = lh ? [size, { lineHeight: lh }] : size;
}
for (const e of effectRecs) T.boxShadow[e.step] = v(e.name);
fs.writeFileSync(path.join(DIST, "theme.json"), JSON.stringify(T, null, 2));
// Scale names for tooling that must know the custom scales (tailwind-merge in @omn1/ui-web).
fs.appendFileSync(
  path.join(GEN, "data.ts"),
  "\n" +
    ts(
      "themeKeys",
      {
        spacing: Object.keys(T.spacing),
        borderRadius: Object.keys(T.borderRadius),
        borderWidth: Object.keys(T.borderWidth),
        fontSize: Object.keys(T.fontSize),
        fontWeight: Object.keys(T.fontWeight),
        letterSpacing: Object.keys(T.letterSpacing),
      },
      "Names of the Tailwind scale entries generated from the tokens.",
    ),
);

// ---- 6. Figma variable map (design-to-code contract) ----------------------------------------------------
// Keys match what get_design_context reports: lower-cased Figma path, spaces → "-"
// e.g. "semantic/surface/neutral/verystrong", "spacement/verysubtle", "system/x2,5".
const figmaKey = (p) => p.toLowerCase().replace(/\s+/g, "-");
const tailwindFor = (r) => {
  const [group, ...rest] = r.path;
  if (group === "key" && rest[0] === "global") {
    return {
      theme: "colors",
      key: rest[1] === "transparent" ? "transparent" : `global.${rest[1]}`,
    };
  }
  if (group === "semantic") {
    const [family, ...tail] = rest;
    return { theme: "colors", key: [family === "opacity" ? "alpha" : family, ...tail].join(".") };
  }
  if (group === "system" && rest[0] !== "9999") return { theme: "spacing", key: rest[0] };
  if (group === "spacement") return { theme: "spacing", key: rest[0] };
  if (group === "border-radius") return { theme: "borderRadius", key: rest[0] };
  if (group === "corner-radius") return { theme: "borderRadius", key: `corner-${rest[0]}` };
  if (group === "stroke") return { theme: "borderWidth", key: rest[0] };
  if (group === "size") return { theme: "fontSize", key: rest[0] };
  if (group === "line-height")
    return { theme: "fontSize", key: rest[0], note: "lineHeight of the fontSize entry" };
  if (group === "weight") return { theme: "fontWeight", key: rest[0] };
  if (group === "letter-spacing") return { theme: "letterSpacing", key: rest[0] };
  if (group === "font-family") return { theme: "fontFamily", key: rest[0] };
  return null; // primitives, key.* (non-global) and alias are CSS-variable only
};
const map = {};
for (const r of lightRecs) {
  if (!r.ext.figma) continue;
  map[figmaKey(r.ext.figma)] = {
    figma: r.ext.figma,
    token: r.name,
    cssVar: cssVar(r.name),
    layer: layerOf(r),
    tailwind: tailwindFor(r),
    ...(r.ext.scopes ? { figmaScopes: r.ext.scopes } : {}),
  };
}
fs.writeFileSync(
  path.join(DIST, "figma-variable-map.json"),
  JSON.stringify(
    {
      generatedFrom: "figma-export",
      prefix: PREFIX,
      variables: map,
      // Figma effect styles (not variables): key = lower-cased style name, e.g. "dropshadow/level-3" → shadow-level-3.
      effects: Object.fromEntries(
        effectRecs.map((e) => [
          figmaKey(e.figma),
          {
            figma: e.figma,
            token: e.name,
            cssVar: cssVar(e.name),
            tailwind: { theme: "boxShadow", key: e.step },
          },
        ]),
      ),
    },
    null,
    2,
  ),
);

const count = (recs, l) => recs.filter((r) => layerOf(r) === l).length;
console.log(
  `tokens built — primitives ${count(lightRecs, "primitives")}, key ${count(lightRecs, "key")}, semantic ${count(lightRecs, "semantic")}, alias ${count(lightRecs, "alias")}, shared ${sharedRecs.length}, display styles ${Object.keys(displayStyles).length}`,
);
